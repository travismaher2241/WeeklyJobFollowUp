import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const wb = Workbook.create();
const s = wb.worksheets.add('Upcoming Jobs');
s.showGridLines = false;
s.getRange('A1:F10').format.font = {name:'Arial',size:11,color:'#243447'};
s.getRange('A1:F10').format.rowHeight = 24;
for (const [col,width] of [['A',52],['B',23],['C',20],['D',20],['E',20],['F',40]]) s.getRange(`${col}1:${col}10`).format.columnWidth=width;
s.getRange('A1:E1').format.rowHeight=94;
const logo=await fs.readFile('templates/plasgain-logo.png');
s.images.add({dataUrl:`data:image/png;base64,${logo.toString('base64')}`,anchor:{from:{row:0,col:0},extent:{widthPx:360,heightPx:360*922/2753}}});
s.getRange('A2:E2').merge();s.getRange('A2').values=[['Upcoming Delivery Dates']];
s.getRange('A2').format.font={name:'Arial',size:16,bold:true,color:'#163A34'};
s.getRange('A2:E2').format.rowHeight=30;
s.getRange('A3:E3').merge();s.getRange('A3').values=[['{{CUSTOMER}}']];s.getRange('A3').format.font={name:'Arial',size:12,bold:true};
s.getRange('A4:E4').merge();s.getRange('A4').values=[['{{SNAPSHOT}}']];
s.getRange('A6:E6').merge();s.getRange('A6').values=[['All dates correct? Reply to the email: “All dates confirmed”.']];
s.getRange('A7:F7').merge();s.getRange('A7').values=[['Changes? Enter a Confirmed Date if firm, or an Estimated Date if provisional. Add any comments, save and email back.']];
s.getRange('A6:E7').format.rowHeight=26;
s.getRange('A9:F9').values=[['Order Description','PO Number','Delivery Date','Confirmed Date','Estimated Date','Comments (optional)']];
s.getRange('A9:F9').format={fill:'#163A34',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},rowHeight:30,horizontalAlignment:'center',verticalAlignment:'center'};
s.getRange('A10:F10').values=[['{{DESCRIPTION}}','{{PO}}',new Date('2026-10-15T00:00:00Z'),null,null,null]];
s.getRange('A10:F10').format.rowHeight=42;
s.getRange('A10:F10').format.verticalAlignment='center';
s.getRange('A10:B10').format.wrapText=true;s.getRange('F10').format.wrapText=true;
s.getRange('C10:E10').setNumberFormat('dd/mm/yyyy');
s.getRange('C10:E10').format.horizontalAlignment='center';
s.getRange('D10:F10').format.fill='#FFF2CC';
s.freezePanes.freezeRows(9);
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:"'Upcoming Jobs'!A9:F10",include:'values,formulas',tableMaxRows:2,tableMaxCols:6})).ndjson);
await (await SpreadsheetFile.exportXlsx(wb)).save('templates/customer-follow-up.xlsx');
const preview=await wb.render({sheetName:'Upcoming Jobs',range:'A1:F10',scale:1.2,format:'png'});
await fs.writeFile('templates/template-preview.png',new Uint8Array(await preview.arrayBuffer()));
